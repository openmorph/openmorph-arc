//! PROOFS — the openmorph-core capability proofs that gate every push: ONE test binary, one module per proof
//! file (the module name is the former `tests/<name>.rs` file name, so a substring filter still selects a proof).
//!
//!     cargo test -p openmorph-core --test proofs                     # the whole tier
//!     cargo test -p openmorph-core --test proofs substrate_deep      # one proof file
//!     cargo nextest run -p openmorph-core -E 'binary(proofs)'
//!
//! The crate — the library and this binary — is built optimized in the dev/test profile (workspace
//! `[profile.dev.package.openmorph-core]`), so the proofs run at speed with debug-assertions and overflow checks
//! still on; the printed numbers are identical to an O0 build (plain f32 arithmetic, no fast-math).
//! `substrate_determinism` pins the default and legacy behaviour of a fixed mixed stream to a full-state hash.
//! The long-running scalability sweeps live in `tests/stress` and the research instruments in `tests/research`,
//! both `#[ignore]`d (see their `main.rs`).

